        got = (rw[0] / 1e18, rw[1] / 1e18, stake(*STRK_T, blk), sum(stake(t, d, blk) for t, d in BTC_T))
        diff = max(abs(g - e) / abs(e) for g, e in zip(got, (srw, brw, sst, bst)))
        worst = max(worst, diff); print(f"block {blk} ({utc(ts).date()}): max rel diff {diff:.1e}")
