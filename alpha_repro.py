DAY = 86400
utc = lambda t: dt.datetime.fromtimestamp(t, dt.timezone.utc)
clamp = lambda x, lo, hi: max(lo, min(hi, x))
ts_list = [s[1] for s in SNAP]

def interp(t, j):
    i = clamp(bisect.bisect_right(ts_list, t) - 1, 0, len(SNAP) - 2)
    a, b = SNAP[i], SNAP[i + 1]
    w = clamp((t - a[1]) / (b[1] - a[1]), 0, 1)
    return a[j] * (1 - w) + b[j] * w

sp = {t // DAY: p for t, p in STRK}
bp = {t // DAY: p for t, p in BTC}

def twap(d, n=7):
    xs = [sp[k] / bp[k] for k in range(d - n + 1, d + 1) if k in sp and k in bp]
    return sum(xs) / len(xs)

ROWS = []  # t, P_STRK, P_BTC, M, S, B
for t, p in STRK:
    if t < SNAP[0][1] or (t // DAY) not in bp:
        continue
    M = (interp(t, 2) + interp(t, 3)) * 8760
    ROWS.append((t, p, bp[t // DAY], M, interp(t, 4), interp(t, 5)))

def target(k, S, B, r):
    return k * (B / r) / (S + k * B / r)

def run(rule):
    """rule(row, a_prev) -> alpha. Returns totals and APR stats."""
    a = 0.25; tS = tU = tB = fS = fU = fB = 0; aprs = []; als = []; over = 0
    for row in ROWS:
        t, p, pb, M, S, B = row
        a = rule(row, a)
        Rb = a / (1 - a) * 0.75 * M / 365; R0 = 0.25 * M / 365
        tS += Rb; tU += Rb * p; tB += Rb * p / pb
        fS += R0; fU += R0 * p; fB += R0 * p / pb
        apr = Rb * 365 * p / (B * pb); aprs.append(apr); als.append(a)
        over += apr > 0.75 * M / S
    n = len(aprs)
    return dict(STRK=tS, USD=tU, BTC=tB, fS=fS, fU=fU, fB=fB, avg=sum(aprs) / n, mx=max(aprs),
                mn=min(aprs), amin=min(als), amax=max(als), over=over)

fixed = lambda row, a: 0.25
original = lambda k: (lambda row, a: clamp(target(k, row[4], row[5], twap(row[0] // DAY)), 0.10, 0.33))

def revised(k, d=0.005, hi=0.33, cut_only=False, use_twap=0):
    def f(row, a):
        t, p, pb, M, S, B = row
        r = twap(t // DAY, use_twap) if use_twap else p / pb
        tg = min(target(k, S, B, r), 0.25 if cut_only else hi)
        g = (1 + d) ** 24
        return min(clamp(tg, a / g, a * g), hi)
    return f

